import type { FastifyInstance } from 'fastify';
import { z } from 'zod';
import { prisma, type Tx } from '../lib/prisma.js';
import { badRequest, conflict, forbidden, notFound } from '../lib/errors.js';
import { num, r2, serialize } from '../lib/serialize.js';
import { authed, ok, type Req } from '../lib/route.js';
import { isManager } from '../lib/auth.js';
import { pageMeta, pageParams, qStr } from '../lib/pagination.js';
import { moveCaisse } from '../lib/caisse.js';
import { resolveStoreId } from '../lib/tenant.js';
import { EXPENSE_CATEGORIES, EXPENSE_METHODS } from '../lib/expenses.js';
import { isOwnUpload, removeUpload } from '../lib/uploads.js';

const expenseSchema = z.object({
  title: z.string().trim().min(1, 'La description est obligatoire').max(200),
  category: z.enum(EXPENSE_CATEGORIES),
  amount: z.coerce.number().positive('Le montant doit être positif').max(10_000_000),
  date: z.coerce.date(),
  paymentMethod: z.enum(EXPENSE_METHODS),
  recipient: z.string().trim().max(200).optional().nullable(),
  notes: z.string().trim().max(2000).optional().nullable(),
  receiptUrl: z.string().max(500).optional().nullable(),
  receiptName: z.string().max(200).optional().nullable(),
  // Idempotency key generated by the form: submitting the same form twice creates one expense.
  clientRef: z.string().max(64).optional().nullable(),
  // Set after the user confirmed a probable duplicate.
  confirmDuplicate: z.boolean().optional(),
});
type ExpenseInput = z.infer<typeof expenseSchema>;

const cashReason = (title: string) => `Dépense - ${title}`;
const reversalReason = (title: string) => `Annulation dépense - ${title}`;
const dayBounds = (d: Date) => [new Date(d.getFullYear(), d.getMonth(), d.getDate()), new Date(d.getFullYear(), d.getMonth(), d.getDate(), 23, 59, 59, 999)] as const;

/**
 * Direct expenses of the business. Cash expenses leave the store's cash drawer; editing or deleting one records
 * the matching reversal in the drawer, and a deleted expense is kept (soft delete) so the history stays complete.
 */
export default async function expenseRoutes(app: FastifyInstance) {
  authed(app);
  const managersOnly = (req: Req) => {
    if (!isManager(req.auth.roles)) throw forbidden('Accès refusé');
  };

  async function checkReceipt(tenantId: string, url: string | null | undefined) {
    if (url && !isOwnUpload(tenantId, url, ['webp', 'jpg', 'png', 'pdf'])) throw badRequest('URL d’image invalide');
  }

  /** Same day, same amount and same description (case-insensitive) as a live expense → probably entered twice. */
  async function findDuplicate(tenantId: string, e: Pick<ExpenseInput, 'title' | 'amount' | 'date'>, exceptId?: string) {
    const [from, to] = dayBounds(e.date);
    const candidates = await prisma.expense.findMany({
      where: { tenantId, deletedAt: null, date: { gte: from, lte: to }, ...(exceptId ? { id: { not: exceptId } } : {}) },
    });
    return candidates.find((c) => r2(num(c.amount)) === r2(e.amount) && c.title.trim().toLowerCase() === e.title.trim().toLowerCase()) ?? null;
  }

  async function cashOut(tx: Tx, tenantId: string, storeId: string | null, amount: number, title: string, userId: string) {
    await moveCaisse(tx, { tenantId, storeId, delta: -amount, type: 'cash_out', reason: cashReason(title), userId });
  }
  async function cashBack(tx: Tx, tenantId: string, storeId: string | null, amount: number, title: string, userId: string) {
    await moveCaisse(tx, { tenantId, storeId, delta: amount, type: 'cash_in', reason: reversalReason(title), userId });
  }

  const presentOne = async (id: string) => {
    const e = await prisma.expense.findUniqueOrThrow({ where: { id } });
    const users = await prisma.user.findMany({ where: { id: { in: [e.createdBy, e.updatedBy].filter(Boolean) as string[] } }, select: { id: true, firstName: true, lastName: true } });
    const u = new Map(users.map((x) => [x.id, x]));
    return serialize({ ...e, creator: e.createdBy ? (u.get(e.createdBy) ?? null) : null, editor: e.updatedBy ? (u.get(e.updatedBy) ?? null) : null });
  };

  app.get('/expenses/categories', async () => ok({ categories: EXPENSE_CATEGORIES, paymentMethods: EXPENSE_METHODS }));

  app.get('/expenses', async (req: Req<unknown, Record<string, string>>) => {
    managersOnly(req);
    const q = req.query;
    const pp = pageParams(q);
    const from = qStr(q.dateFrom);
    const to = qStr(q.dateTo);
    const query = qStr(q.query);
    const where = {
      tenantId: req.auth.tenantId,
      deletedAt: null,
      ...(qStr(q.category) ? { category: q.category } : {}),
      ...(qStr(q.paymentMethod) ? { paymentMethod: q.paymentMethod } : {}),
      ...(from || to ? { date: { ...(from ? { gte: new Date(`${from}T00:00:00`) } : {}), ...(to ? { lte: new Date(`${to}T23:59:59.999`) } : {}) } } : {}),
      ...(query ? { OR: [{ title: { contains: query } }, { recipient: { contains: query } }, { notes: { contains: query } }] } : {}),
    };
    const [rows, total, all] = await Promise.all([
      prisma.expense.findMany({ where, orderBy: [{ date: 'desc' }, { createdAt: 'desc' }], skip: pp.skip, take: pp.limit }),
      prisma.expense.count({ where }),
      prisma.expense.findMany({ where, select: { amount: true } }),
    ]);
    return ok({
      expenses: serialize(rows),
      meta: pageMeta(total, pp),
      totals: { count: total, amount: r2(all.reduce((s, e) => s + num(e.amount), 0)) },
    });
  });

  app.get('/expenses/:id', async (req: Req<unknown, unknown, { id: string }>) => {
    managersOnly(req);
    const e = await prisma.expense.findFirst({ where: { id: req.params.id, tenantId: req.auth.tenantId } });
    if (!e) throw notFound('Expense', req.params.id);
    return ok({ expense: await presentOne(e.id) });
  });

  app.post('/expenses', async (req: Req<ExpenseInput>, reply) => {
    managersOnly(req);
    const input = expenseSchema.parse(req.body);
    const tenantId = req.auth.tenantId;
    if (input.clientRef) {
      const again = await prisma.expense.findFirst({ where: { tenantId, clientRef: input.clientRef } });
      if (again) return ok({ expense: await presentOne(again.id), duplicateOf: null, replayed: true });
    }
    await checkReceipt(tenantId, input.receiptUrl);
    if (!input.confirmDuplicate) {
      const dup = await findDuplicate(tenantId, input);
      if (dup) throw conflict(`Dépense similaire déjà enregistrée le même jour (${dup.title})`);
    }
    const storeId = await resolveStoreId(tenantId, req.auth.storeId);
    const created = await prisma.$transaction(async (tx) => {
      const e = await tx.expense.create({
        data: {
          tenantId,
          storeId,
          title: input.title,
          category: input.category,
          amount: r2(input.amount),
          date: input.date,
          paymentMethod: input.paymentMethod,
          recipient: input.recipient || null,
          notes: input.notes || null,
          receiptUrl: input.receiptUrl || null,
          receiptName: input.receiptName || null,
          clientRef: input.clientRef || null,
          createdBy: req.auth.userId,
        },
      });
      if (e.paymentMethod === 'cash') await cashOut(tx, tenantId, storeId, r2(input.amount), e.title, req.auth.userId);
      return e;
    });
    reply.status(201);
    return ok({ expense: await presentOne(created.id) });
  });

  app.put('/expenses/:id', async (req: Req<Partial<ExpenseInput>, unknown, { id: string }>) => {
    managersOnly(req);
    const tenantId = req.auth.tenantId;
    const existing = await prisma.expense.findFirst({ where: { id: req.params.id, tenantId, deletedAt: null } });
    if (!existing) throw notFound('Expense', req.params.id);
    const input = expenseSchema.partial().parse(req.body);
    const next = {
      title: input.title ?? existing.title,
      amount: input.amount ?? num(existing.amount),
      date: input.date ?? existing.date,
      paymentMethod: input.paymentMethod ?? existing.paymentMethod,
    };
    if (input.receiptUrl !== undefined) await checkReceipt(tenantId, input.receiptUrl);
    if (!input.confirmDuplicate && (input.title !== undefined || input.amount !== undefined || input.date !== undefined)) {
      const dup = await findDuplicate(tenantId, next, existing.id);
      if (dup) throw conflict(`Dépense similaire déjà enregistrée le même jour (${dup.title})`);
    }
    const oldAmount = r2(num(existing.amount));
    const cashChanged = existing.paymentMethod !== next.paymentMethod || oldAmount !== r2(next.amount);
    await prisma.$transaction(async (tx) => {
      await tx.expense.update({
        where: { id: existing.id },
        data: {
          ...(input.title !== undefined && { title: input.title }),
          ...(input.category !== undefined && { category: input.category }),
          ...(input.amount !== undefined && { amount: r2(input.amount) }),
          ...(input.date !== undefined && { date: input.date }),
          ...(input.paymentMethod !== undefined && { paymentMethod: input.paymentMethod }),
          ...(input.recipient !== undefined && { recipient: input.recipient || null }),
          ...(input.notes !== undefined && { notes: input.notes || null }),
          ...(input.receiptUrl !== undefined && { receiptUrl: input.receiptUrl || null }),
          ...(input.receiptName !== undefined && { receiptName: input.receiptName || null }),
          updatedBy: req.auth.userId,
        },
      });
      // The drawer only follows cash: undo the old cash movement, record the new one.
      if (cashChanged) {
        if (existing.paymentMethod === 'cash') await cashBack(tx, tenantId, existing.storeId, oldAmount, existing.title, req.auth.userId);
        if (next.paymentMethod === 'cash') await cashOut(tx, tenantId, existing.storeId, r2(next.amount), next.title, req.auth.userId);
      }
    });
    if (input.receiptUrl !== undefined && input.receiptUrl !== existing.receiptUrl) await removeUpload(tenantId, existing.receiptUrl);
    return ok({ expense: await presentOne(existing.id) });
  });

  app.delete('/expenses/:id', async (req: Req<unknown, unknown, { id: string }>) => {
    managersOnly(req);
    const tenantId = req.auth.tenantId;
    const existing = await prisma.expense.findFirst({ where: { id: req.params.id, tenantId, deletedAt: null } });
    if (!existing) throw notFound('Expense', req.params.id);
    await prisma.$transaction(async (tx) => {
      await tx.expense.update({ where: { id: existing.id }, data: { deletedAt: new Date(), deletedBy: req.auth.userId } });
      if (existing.paymentMethod === 'cash') await cashBack(tx, tenantId, existing.storeId, r2(num(existing.amount)), existing.title, req.auth.userId);
    });
    return ok({ deleted: true });
  });
}
